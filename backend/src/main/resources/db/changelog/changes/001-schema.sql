    CONSTRAINT fk_assessment_user FOREIGN KEY (evaluated_by_id) REFERENCES app_user (id),
    CONSTRAINT ck_assessment_kind CHECK (kind IN ('INTERACTION', 'ENTRANCE_TEST'))
);
CREATE INDEX ix_assessment_application ON assessment (application_id);

