-- Append-only in the application code (no update or delete paths exist)
CREATE TABLE stage_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT NOT NULL,
    from_stage_id   BIGINT,
    to_stage_id     BIGINT NOT NULL,
    actor_type      VARCHAR(20) NOT NULL,
    actor_id        VARCHAR(50),
    reason          VARCHAR(300),
    changed_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_history_application FOREIGN KEY (application_id) REFERENCES application (id),
    CONSTRAINT fk_history_from FOREIGN KEY (from_stage_id) REFERENCES stage_definition (id),
    CONSTRAINT fk_history_to FOREIGN KEY (to_stage_id) REFERENCES stage_definition (id),
    CONSTRAINT ck_history_actor CHECK (actor_type IN ('GUARDIAN', 'STAFF', 'SYSTEM'))
);
CREATE INDEX ix_history_application ON stage_history (application_id, id);

-- Transactional outbox: written in the same transaction as the state change, relayed by OutboxRelay
CREATE TABLE outbox_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type  VARCHAR(40) NOT NULL,
    aggregate_id    BIGINT NOT NULL,
    event_type      VARCHAR(60) NOT NULL,
    payload         TEXT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at    TIMESTAMP WITH TIME ZONE,
    attempts        INT NOT NULL DEFAULT 0
);
CREATE INDEX ix_outbox_pending ON outbox_event (published_at, id);

