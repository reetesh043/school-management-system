CREATE TABLE invoice (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      VARCHAR(40) NOT NULL,
    application_id  BIGINT NOT NULL,
    description     VARCHAR(200) NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3) NOT NULL DEFAULT 'INR',
    status          VARCHAR(20) NOT NULL DEFAULT 'ISSUED',
    issued_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_invoice_no UNIQUE (invoice_no),
    CONSTRAINT fk_invoice_application FOREIGN KEY (application_id) REFERENCES application (id),
    CONSTRAINT ck_invoice_status CHECK (status IN ('ISSUED', 'PAID', 'CANCELLED', 'EXPIRED'))
);
CREATE INDEX ix_invoice_application ON invoice (application_id, status);

CREATE TABLE payment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          BIGINT NOT NULL,
    gateway             VARCHAR(30) NOT NULL,
    gateway_order_id    VARCHAR(100) NOT NULL,
    gateway_payment_id  VARCHAR(100),
    idempotency_key     VARCHAR(100) NOT NULL,
    amount              NUMERIC(12, 2) NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'INITIATED',
    method              VARCHAR(20),
    settled_at          TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (id),
    CONSTRAINT uq_payment_idempotency UNIQUE (idempotency_key),
    CONSTRAINT uq_payment_order UNIQUE (gateway, gateway_order_id),
    CONSTRAINT ck_payment_status CHECK (status IN ('INITIATED', 'SUCCESS', 'FAILED', 'REFUNDED'))
);

