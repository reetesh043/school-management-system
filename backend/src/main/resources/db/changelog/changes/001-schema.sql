-- One ledger row per application. The status moves HELD -> CONFIRMED, or RELEASED when the seat is given back.
CREATE TABLE seat_allocation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_config_id  BIGINT NOT NULL,
    application_id   BIGINT NOT NULL,
    status           VARCHAR(20) NOT NULL,
    held_until       TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_seat_class FOREIGN KEY (class_config_id) REFERENCES class_config (id),
    CONSTRAINT fk_seat_application FOREIGN KEY (application_id) REFERENCES application (id),
    CONSTRAINT uq_seat_application UNIQUE (application_id),
    CONSTRAINT ck_seat_status CHECK (status IN ('HELD', 'CONFIRMED', 'RELEASED'))
);
CREATE INDEX ix_seat_class ON seat_allocation (class_config_id, status);

CREATE TABLE interaction_slot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(20) NOT NULL,
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity   INT NOT NULL,
    booked     INT NOT NULL DEFAULT 0,
    CONSTRAINT ck_slot_kind CHECK (kind IN ('INTERACTION', 'CAMPUS_TOUR', 'ENTRANCE_TEST')),
    CONSTRAINT ck_slot_capacity CHECK (capacity > 0 AND booked >= 0 AND booked <= capacity)
);

CREATE TABLE interaction_booking (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id         BIGINT NOT NULL,
    application_id  BIGINT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    CONSTRAINT fk_booking_slot FOREIGN KEY (slot_id) REFERENCES interaction_slot (id),
    CONSTRAINT fk_booking_application FOREIGN KEY (application_id) REFERENCES application (id),
    CONSTRAINT uq_booking UNIQUE (slot_id, application_id),
    CONSTRAINT ck_booking_status CHECK (status IN ('BOOKED', 'ATTENDED', 'NO_SHOW', 'CANCELLED'))
);

CREATE TABLE assessment (
