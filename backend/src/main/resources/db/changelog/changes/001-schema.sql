--changeset admissions:001-workflow-and-classes
--comment Academic years, workflow definition (stages, transitions) and per-class configuration

CREATE TABLE academic_year (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label            VARCHAR(20) NOT NULL,
    starts_on        DATE NOT NULL,
    ends_on          DATE NOT NULL,
    age_cutoff_date  DATE NOT NULL,
    admissions_open  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_academic_year_label UNIQUE (label)
);

CREATE TABLE workflow (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    version  INT NOT NULL DEFAULT 1,
    status   VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT uq_workflow UNIQUE (name, version),
    CONSTRAINT ck_workflow_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE TABLE stage_definition (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id  BIGINT NOT NULL,
    code         VARCHAR(30) NOT NULL,
    name         VARCHAR(60) NOT NULL,
    seq_no       INT NOT NULL,
    category     VARCHAR(20) NOT NULL,
    CONSTRAINT fk_stage_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id),
    CONSTRAINT uq_stage_code UNIQUE (workflow_id, code),
    CONSTRAINT ck_stage_category CHECK (category IN ('OPEN', 'HOLD', 'TERMINAL_SUCCESS', 'TERMINAL_FAIL'))
);

-- allowed_roles / guard_keys / action_keys are comma-separated lists so the schema stays portable
CREATE TABLE stage_transition (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id    BIGINT NOT NULL,
    from_stage_id  BIGINT NOT NULL,
    to_stage_id    BIGINT NOT NULL,
    allowed_roles  VARCHAR(255) NOT NULL,
    guard_keys     VARCHAR(255) NOT NULL DEFAULT '',
    action_keys    VARCHAR(255) NOT NULL DEFAULT '',
    CONSTRAINT fk_transition_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id),
    CONSTRAINT fk_transition_from FOREIGN KEY (from_stage_id) REFERENCES stage_definition (id),
    CONSTRAINT fk_transition_to FOREIGN KEY (to_stage_id) REFERENCES stage_definition (id),
    CONSTRAINT uq_transition UNIQUE (from_stage_id, to_stage_id)
);

CREATE TABLE class_config (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id  BIGINT NOT NULL,
    class_code        VARCHAR(20) NOT NULL,
    display_name      VARCHAR(60) NOT NULL,
    min_age_years     INT,
    max_age_years     INT,
    seats_total       INT NOT NULL,
    seats_pre_filled  INT NOT NULL DEFAULT 0,
    pass_mark         NUMERIC(5, 2) NOT NULL DEFAULT 50,
    admission_fee     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    fee_due_days      INT NOT NULL DEFAULT 5,
    workflow_id       BIGINT NOT NULL,
    CONSTRAINT fk_class_year FOREIGN KEY (academic_year_id) REFERENCES academic_year (id),
    CONSTRAINT fk_class_workflow FOREIGN KEY (workflow_id) REFERENCES workflow (id),
    CONSTRAINT uq_class UNIQUE (academic_year_id, class_code),
    CONSTRAINT ck_class_seats CHECK (seats_total >= 0 AND seats_pre_filled >= 0)
);

CREATE TABLE required_document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_config_id  BIGINT NOT NULL,
    doc_type         VARCHAR(30) NOT NULL,
    mandatory        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_reqdoc_class FOREIGN KEY (class_config_id) REFERENCES class_config (id) ON DELETE CASCADE,
    CONSTRAINT uq_reqdoc UNIQUE (class_config_id, doc_type)
);

